import { expect, test } from '@playwright/test'
import { startStudio } from './fixtures/workbench/studio.ts'
import type { Studio } from './fixtures/workbench/studio.ts'
const FIXTURE = fileURLToPath(new URL('./fixtures/block-editor', import.meta.url))
let studio: Studio
test.use({ locale: 'zh-CN', actionTimeout: 20_000 })
test.describe.configure({ timeout: 180_000 })
test.beforeAll(async () => {
  if (!existsSync(join(FIXTURE, 'node_modules'))) symlinkSync(fileURLToPath(new URL('../examples/animations/node_modules', import.meta.url)), join(FIXTURE, 'node_modules'), 'junction')
  studio = await startStudio({ port: 5795, prefix: 'block-editor', fixture: FIXTURE, isolateClient: true, onServiceOutput: text => appendFileSync('/private/tmp/block-editor-service.log', text) })
})
test.afterAll(async () => studio?.close())
test('edits body blocks, preserves narration, seeks animation steps and edits their timing', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const body = frame.locator('[data-section="intro"] .tiptap')
  await expect(body).toBeVisible({ timeout: 60_000 })
  await expect(body).toContainText('可编辑的正文。')
  await expect(body).not.toContainText('独立的讲解文本。')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('正文已经通过块编辑器修改。')
  await expect(frame.locator('[data-section="intro"] .pm-block-editor__status')).not.toHaveText('已保存')
  const file = join(studio.workspace.dir, 'zh/lecture.md')
  await expect.poll(() => readFileSync(file, 'utf8'), { timeout: 30_000 }).toContain('正文已经通过块编辑器修改。')
  expect(readFileSync(file, 'utf8')).toContain('独立的讲解文本。')
  await expect(body).toContainText('正文已经通过块编辑器修改。')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('第一次快速修改。')
  await body.press('Meta+s')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('切换放映前的最终正文。')
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('切换放映前的最终正文。')
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '文档', exact: true }).click()
  await expect(body).toContainText('切换放映前的最终正文。')
  const scene = frame.locator('[data-section="animation"] .pm-scene')
  await scene.scrollIntoViewIfNeeded()
  await expect(scene).toHaveAttribute('data-status', 'ready')
  await frame.locator('[data-section="animation"]').getByRole('button', { name: '跳到动画第 2 步', exact: true }).click()
  const narration = page.getByRole('region', { name: '步骤讲解', exact: true })
  const text = narration.getByRole('textbox', { name: '讲解文本', exact: true })
  await expect(text).toHaveValue('第二步的讲解。')
  await text.fill('第二步更新后的讲解。')
  await narration.getByRole('button', { name: '与动画同步', exact: true }).click()
  await narration.getByRole('button', { name: '保存', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('第二步更新后的讲解。')
  await expect(narration.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
  await expect(frame.locator('.pm-present')).toBeVisible()
  await expect(frame.locator('.pm-present')).toHaveAttribute('data-step', '1')
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    await expect(frame.locator('.pm-present')).toBeVisible()
    await page.screenshot({ path: test.info().outputPath(`blocks-${width}-${scheme}.png`) })
    expect(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  expect(errors).toEqual([])
})

test('edits the current animation source and configuration, preserves conflicts, and creates independent animation blocks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error' && message.text().startsWith('[presmium.')) errors.push(message.text())
  })
  const file = join(studio.workspace.dir, 'zh/lecture.md')
  const original = readFileSync(file, 'utf8')
  const definition = join(studio.workspace.dir, 'zh/scenes/steps.ts')
  const originalCode = readFileSync(definition, 'utf8')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const animation = frame.locator('[data-section="animation"]')
  await animation.scrollIntoViewIfNeeded()
  await expect(animation.locator('.tiptap')).toBeVisible()
  await expect(animation.locator('.pm-scene')).toHaveCount(1)
  await expect(animation.getByRole('button', { name: '更换动画…', exact: true })).toHaveCount(0)
  await animation.getByRole('button', { name: '跳到动画第 2 步', exact: true }).click()
  const source = animation.locator('.pm-source-block')
  await source.getByRole('button', { name: '源码', exact: true }).click()
  const code = source.locator('.cm-content[aria-label="源码编辑器"]')
  await expect(code).toContainText('gsapScene')
  await code.click()
  await code.press('Meta+A')
  await page.keyboard.insertText('export default {')
  await expect(page.locator('.pmw-toolbar__status')).toHaveAttribute('data-save', 'dirty')
  await source.getByRole('button', { name: '预览', exact: true }).click()
  await expect(source.getByRole('alert')).toBeVisible()
  await expect(source).toHaveAttribute('data-source-mode', 'source')
  expect(readFileSync(definition, 'utf8')).toBe(originalCode)
  const edited = originalCode.replace('class="step-box"', 'class="step-box" data-source-edit="updated"')
  await code.click()
  await code.press('Meta+A')
  await page.keyboard.insertText(edited)
  await source.getByRole('button', { name: '预览', exact: true }).click()
  await expect.poll(() => readFileSync(definition, 'utf8')).toBe(edited)
  await expect(source.locator('.step-box[data-source-edit="updated"]')).toBeVisible({ timeout: 60_000 })
  await expect(page.locator('.pmw-toolbar__status')).toHaveAttribute('data-save', 'saved')
  await expect(page.getByRole('button', { name: '第 2 页 · 第 2 步', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(animation.locator('.pm-scene__step[aria-pressed="true"]')).toHaveText('2')
  expect(readFileSync(file, 'utf8')).toBe(original)
  await expect(animation.locator('.pm-scene')).toHaveCount(1)

  await source.getByRole('button', { name: '源码', exact: true }).click()
  await source.getByRole('button', { name: '配置', exact: true }).click()
  await expect(code).toContainText(':durations: 800ms, 1200ms, 1000ms')
  const config = await code.innerText()
  await code.click()
  await code.press('Meta+A')
  await page.keyboard.insertText(config.replace('800ms', '900ms'))
  await source.getByRole('button', { name: '预览', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8')).toContain(':durations: 900ms, 1200ms, 1000ms')
  expect(readFileSync(definition, 'utf8')).toBe(edited)

  await source.getByRole('button', { name: '源码', exact: true }).click()
  await source.getByRole('button', { name: '代码', exact: true }).click()
  await expect(code).toContainText('data-source-edit="updated"')
  await code.click()
  await code.press('Meta+A')
  await page.keyboard.insertText(`${edited}\n// local draft\n`)
  const external = `${edited}\n// external change\n`
  writeFileSync(definition, external)
  await source.getByRole('button', { name: '保存源码', exact: true }).click()
  await expect(source.getByRole('alert')).toContainText('草稿已保留')
  await expect(code).toContainText('local draft')
  expect(readFileSync(definition, 'utf8')).toBe(external)
  await source.getByRole('button', { name: '重新加载源码', exact: true }).click()
  await expect(code).toContainText('external change')
  await expect(code).not.toContainText('local draft')
  await source.getByRole('button', { name: '预览', exact: true }).click()

  const empty = frame.locator('[data-section="empty"]')
  await empty.scrollIntoViewIfNeeded()
  const blank = empty.locator('.tiptap')
  await expect(blank).toBeVisible()
  const beforeFiles = readdirSync(join(studio.workspace.dir, 'zh/scenes'))
  const beforeCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: studio.workspace.dir, encoding: 'utf8' }).trim()
  await blank.click()
  await page.keyboard.insertText('/')
  await frame.getByRole('option', { name: '动画', exact: true }).click()
  const created = empty.locator('.pm-source-block')
  await expect(created).toHaveAttribute('data-source-mode', 'source', { timeout: 60_000 })
  await expect(created.locator('.cm-content')).toContainText('gsapScene')
  const newFiles = readdirSync(join(studio.workspace.dir, 'zh/scenes')).filter(name => !beforeFiles.includes(name))
  expect(newFiles).toHaveLength(1)
  expect(readFileSync(file, 'utf8')).toContain(newFiles[0]!.replace(/\.ts$/, ''))
  const afterCommit = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: studio.workspace.dir, encoding: 'utf8' }).trim()
  expect(afterCommit).not.toBe(beforeCommit)
  expect(execFileSync('git', ['diff-tree', '--no-commit-id', '--name-only', '-r', afterCommit], { cwd: studio.workspace.dir, encoding: 'utf8' }).trim().split('\n').sort()).toEqual(['zh/lecture.md', `zh/scenes/${newFiles[0]}`].sort())
  await created.getByRole('button', { name: '预览', exact: true }).click()
  await expect(created.locator('.pm-scene')).toHaveAttribute('data-status', 'ready', { timeout: 60_000 })
  await created.getByRole('button', { name: '源码', exact: true }).click()
  await page.getByRole('button', { name: '关闭导航窗格', exact: true }).click()
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    const panel = page.getByRole('region', { name: '步骤讲解', exact: true })
    if (await panel.isVisible()) await panel.getByRole('button', { name: '关闭', exact: true }).click()
    await created.scrollIntoViewIfNeeded()
    await page.screenshot({ path: test.info().outputPath(`source-${width}-${scheme}.png`) })
    expect(await created.locator('.pm-source-block__toolbar').evaluate(e => e.scrollWidth <= e.clientWidth + 1)).toBe(true)
    expect(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  expect(errors).toEqual([])
})

test('reveals the content of later steps instead of returning to the page heading', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const section = frame.locator('[data-section="late"]')
  await section.locator('.pm-section__title [data-narration-step]').click()
  const panel = page.getByRole('region', { name: '步骤讲解', exact: true })
  const scene = section.locator('[data-block="late-third"] .pm-scene').first()
  for (const step of [8, 9, 10, 11]) {
    await panel.getByRole('button', { name: `第 4 页 · 第 ${step + 1} 步`, exact: true }).click()
    await expect(scene).toBeInViewport({ ratio: .5 })
    await expect(scene).toHaveAttribute('data-status', 'ready')
    await expect(scene).toHaveAttribute('data-position', String((step - 7) * 1000))
  }
  await page.getByRole('button', { name: '关闭导航窗格', exact: true }).click()
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    if (width < 768 && await page.locator('.pmw-navigation').isVisible())
      await page.getByRole('button', { name: '关闭导航窗格', exact: true }).click()
    if (!await panel.isVisible())
      await page.locator('.pmw-toolbar').getByRole('button', { name: '步骤讲解', exact: true }).click()
    await panel.getByRole('button', { name: '第 4 页 · 第 9 步', exact: true }).click()
    if (width < 768) await panel.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(scene).toBeInViewport({ ratio: .5 })
    await page.screenshot({ path: test.info().outputPath(`late-step-${width}-${scheme}.png`) })
  }
  expect(errors).toEqual([])
})

test('creates independent pages from navigation and the block menu after saving the current body', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (message.type() === 'error' && message.text().startsWith('[presmium.')) errors.push(message.text())
  })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const originalPages = await frame.locator('.pm-section').count()
  const intro = frame.locator('[data-section="intro"] .tiptap')
  await intro.click()
  await intro.press('Meta+A')
  await page.keyboard.insertText('新建页面前的正文草稿。')
  await expect(page.locator('.pmw-navigation__item[aria-current="location"]')).toContainText('正文页面')
  // This click must flush the draft, without waiting for the editor's autosave debounce.
  await page.getByRole('button', { name: '新建页面', exact: true }).click()
  const added = frame.locator('.pm-section[data-section^="page-"]').first()
  await expect(added.locator('.tiptap')).toBeFocused({ timeout: 60_000 })
  await expect(frame.locator('.pm-section')).toHaveCount(originalPages + 1)
  const firstId = await added.getAttribute('data-section')
  expect(await frame.locator('.pm-section').evaluateAll(elements => elements.slice(0, 3).map(e => e.getAttribute('data-section')))).toEqual(['intro', firstId, 'animation'])
  const file = join(studio.workspace.dir, 'zh/lecture.md')
  expect(readFileSync(file, 'utf8')).toContain('新建页面前的正文草稿。')
  expect(readFileSync(file, 'utf8')).toContain('独立的讲解文本。')
  await page.keyboard.insertText('独立页面的正文。')
  await added.locator('.tiptap').press('Meta+s')
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('独立页面的正文。')
  await expect(intro).not.toContainText('独立页面的正文。')

  await added.locator('.tiptap').click()
  await added.locator('.tiptap').press('Meta+A')
  await added.locator('.tiptap').press('ArrowRight')
  await added.locator('.tiptap').press('Enter')
  await page.keyboard.insertText('/')
  await frame.getByRole('option', { name: '新建页面', exact: true }).click()
  await expect(frame.locator('.pm-section')).toHaveCount(originalPages + 2)
  const second = frame.locator('.pm-section[data-section^="page-"]').nth(1)
  await expect(second.locator('.tiptap')).toBeFocused()
  const secondId = await second.getAttribute('data-section')
  await page.locator('.pmw-toolbar').getByRole('button', { name: /^撤消：新建页面/ }).click()
  await expect(frame.locator(`.pm-section[data-section="${secondId}"]`)).toHaveCount(0)
  await expect(frame.locator('.pm-section')).toHaveCount(originalPages + 1)
  await page.locator('.pmw-toolbar').getByRole('button', { name: /^恢复：新建页面/ }).click()
  await expect(frame.locator(`.pm-section[data-section="${secondId}"]`)).toHaveCount(1)
  await page.locator('.pmw-navigation__item').nth(1).click()
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
  await expect(frame.locator('.pm-present')).toHaveAttribute('data-section', firstId!)
  await expect(frame.locator('.pm-present')).toContainText('独立页面的正文。')
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '文档', exact: true }).click()
  const retainedScene = frame.locator('[data-section="animation"] .pm-scene')
  await retainedScene.scrollIntoViewIfNeeded()
  await expect(retainedScene).toHaveAttribute('data-status', 'ready', { timeout: 20_000 })
  const frameTime = await retainedScene.evaluate(() => performance.timeOrigin)
  const sceneFile = join(studio.workspace.dir, 'zh/scenes/steps.ts')
  writeFileSync(sceneFile, readFileSync(sceneFile, 'utf8').replace('xPercent: 100', 'xPercent: 101'))
  await expect.poll(() => frame.locator('html').evaluate(() => performance.timeOrigin), { timeout: 60_000 }).not.toBe(frameTime)
  await expect(frame.locator('.pm-section')).toHaveCount(originalPages + 2)
  await retainedScene.scrollIntoViewIfNeeded()
  await expect(retainedScene).toHaveAttribute('data-status', 'ready')
  await added.scrollIntoViewIfNeeded()
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    const narration = page.getByRole('region', { name: '步骤讲解', exact: true })
    if (await narration.isVisible()) await narration.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(page.getByRole('button', { name: '新建页面', exact: true })).toBeVisible()
    await page.screenshot({ path: test.info().outputPath(`pages-${width}-${scheme}.png`) })
    expect(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  expect(errors).toEqual([])
})
