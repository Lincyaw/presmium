import { appendFileSync, existsSync, readFileSync, symlinkSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { expect, test } from '@playwright/test'
import { startStudio } from './fixtures/workbench/studio.ts'
import type { Studio } from './fixtures/workbench/studio.ts'
const FIXTURE = fileURLToPath(new URL('./fixtures/block-editor', import.meta.url))
let studio: Studio
test.use({ locale: 'zh-CN', actionTimeout: 20_000 })
test.describe.configure({ timeout: 180_000 })
test.beforeAll(async () => {
  if (!existsSync(join(FIXTURE, 'node_modules'))) symlinkSync(fileURLToPath(new URL('../examples/animations/node_modules', import.meta.url)), join(FIXTURE, 'node_modules'), 'junction')
  studio = await startStudio({ port: 5795, prefix: 'block-editor', fixture: FIXTURE, isolateClient: true, onServiceOutput: text => appendFileSync('/private/tmp/block-editor-service.log', text) })
})
test.afterAll(async () => studio?.close())
test('edits body blocks, preserves narration, seeks animation steps and edits their timing', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const body = frame.locator('[data-section="intro"] .tiptap')
  await expect(body).toBeVisible({ timeout: 60_000 })
  await expect(body).toContainText('可编辑的正文。')
  await expect(body).not.toContainText('独立的讲解文本。')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('正文已经通过块编辑器修改。')
  await expect(frame.locator('[data-section="intro"] .pm-block-editor__status')).not.toHaveText('已保存')
  const file = join(studio.workspace.dir, 'zh/lecture.md')
  await expect.poll(() => readFileSync(file, 'utf8'), { timeout: 30_000 }).toContain('正文已经通过块编辑器修改。')
  expect(readFileSync(file, 'utf8')).toContain('独立的讲解文本。')
  await expect(body).toContainText('正文已经通过块编辑器修改。')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('第一次快速修改。')
  await body.press('Meta+s')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('切换放映前的最终正文。')
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('切换放映前的最终正文。')
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '文档', exact: true }).click()
  await expect(body).toContainText('切换放映前的最终正文。')
  const scene = frame.locator('[data-section="animation"] .pm-scene')
  await scene.scrollIntoViewIfNeeded()
  await expect(scene).toHaveAttribute('data-status', 'ready')
  await frame.locator('[data-section="animation"]').getByRole('button', { name: '跳到动画第 2 步', exact: true }).click()
  const narration = page.getByRole('region', { name: '步骤讲解', exact: true })
  const text = narration.getByRole('textbox', { name: '讲解文本', exact: true })
  await expect(text).toHaveValue('第二步的讲解。')
  await text.fill('第二步更新后的讲解。')
  await narration.getByRole('button', { name: '与动画同步', exact: true }).click()
  await narration.getByRole('button', { name: '保存', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('第二步更新后的讲解。')
  await expect(narration.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
  await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
  await expect(frame.locator('.pm-present')).toBeVisible()
  await expect(frame.locator('.pm-present')).toHaveAttribute('data-step', '1')
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    await expect(frame.locator('.pm-present')).toBeVisible()
    await page.screenshot({ path: test.info().outputPath(`blocks-${width}-${scheme}.png`) })
    expect(await page.locator('body').evaluate(e => e.scrollWidth <= innerWidth + 1)).toBe(true)
  }
  expect(errors).toEqual([])
})

test('inserts a chosen scene once and keeps the block count across saves and reopening', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const file = join(studio.workspace.dir, 'zh/lecture.md')
  const original = readFileSync(file, 'utf8')
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const empty = frame.locator('[data-section="empty"]')
  await empty.scrollIntoViewIfNeeded()
  await expect(empty.locator('.tiptap')).toBeVisible({ timeout: 60_000 })
  await expect(empty.locator('.pm-block-editor__status')).toHaveText('已保存')
  const animation = frame.locator('[data-section="animation"]')
  await animation.scrollIntoViewIfNeeded()
  await expect(animation.locator('.tiptap')).toBeVisible()
  await expect(animation.locator('.pm-scene')).toHaveCount(1)
  await page.locator('.pmw-navigation button').first().click()
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    if (width < 768 && await page.locator('.pmw-navigation').isVisible())
      await page.locator('.pmw-navigation button').first().click()
    await animation.getByRole('button', { name: '插入动画', exact: true }).click()
    await expect(frame.getByRole('menuitem', { name: '动画页面', exact: true })).toBeVisible()
    expect(await frame.getByRole('menuitem', { name: '动画页面', exact: true }).locator('svg').evaluate(el => el.getBoundingClientRect().width)).toBeLessThanOrEqual(32)
    await page.screenshot({ path: test.info().outputPath(`insert-menu-${width}-${scheme}.png`) })
    await page.keyboard.press('Escape')
    await expect(animation.locator('.pm-scene')).toHaveCount(1)
  }
  expect(readFileSync(file, 'utf8')).toBe(original)
  await page.setViewportSize({ width: 1440, height: 1000 })
  await animation.getByRole('button', { name: '插入动画', exact: true }).click()
  await frame.getByRole('menuitem', { name: '动画页面', exact: true }).click()
  await expect(animation.locator('.pm-scene')).toHaveCount(2)
  await expect.poll(() => readFileSync(file, 'utf8').match(/\{scene\} steps/g)?.length).toBe(2)
  const first = animation.locator('.pm-block-editor__scene').first()
  await expect(first.locator('.pm-block-editor__scene-name')).toHaveText('动画页面')
  await expect(first.getByRole('combobox')).toHaveCount(0)
  await first.getByRole('button', { name: '更换动画…', exact: true }).click()
  await frame.getByRole('menuitem', { name: '分步定位', exact: true }).click()
  await expect(first.locator('.pm-scene')).toHaveAttribute('data-scene', 'later')
  await expect.poll(() => readFileSync(file, 'utf8').match(/\{scene\} steps/g)?.length).toBe(1)
  await first.getByRole('button', { name: '更换动画…', exact: true }).click()
  await frame.getByRole('menuitem', { name: '动画页面', exact: true }).click()
  await expect.poll(() => readFileSync(file, 'utf8').match(/\{scene\} steps/g)?.length).toBe(2)
  const body = frame.locator('[data-section="intro"] .tiptap')
  await body.click()
  await body.press('Meta+A')
  await page.keyboard.insertText('插入动画后的再次保存。')
  await expect.poll(() => readFileSync(file, 'utf8')).toContain('插入动画后的再次保存。')
  expect(readFileSync(file, 'utf8').match(/\{scene\} steps/g)).toHaveLength(2)
  for (let i = 0; i < 2; i++) {
    await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '放映', exact: true }).click()
    await expect(frame.locator('.pm-present')).toBeVisible()
    await page.getByRole('group', { name: '视图', exact: true }).getByRole('button', { name: '文档', exact: true }).click()
    await animation.scrollIntoViewIfNeeded()
    await expect(animation.locator('.pm-scene')).toHaveCount(2)
  }
  const preview = await (await page.locator('.pmw-preview__frame[data-renderer="web"]').elementHandle())!.contentFrame()
  await preview!.goto(preview!.url())
  await animation.scrollIntoViewIfNeeded()
  await expect(animation.locator('.tiptap')).toBeVisible({ timeout: 60_000 })
  await expect(animation.locator('.pm-scene')).toHaveCount(2)
  expect(readFileSync(file, 'utf8').match(/\{scene\} steps/g)).toHaveLength(2)
  expect(errors).toEqual([])
})

test('reveals the content of later steps instead of returning to the page heading', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1000 })
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '块编辑' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview[data-ready="true"]')).toBeVisible({ timeout: 90_000 })
  const frame = page.frameLocator('.pmw-preview__frame[data-renderer="web"]')
  const section = frame.locator('[data-section="late"]')
  await section.locator('.pm-section__title [data-narration-step]').click()
  const panel = page.getByRole('region', { name: '步骤讲解', exact: true })
  const scene = section.locator('[data-block="late-third"] .pm-scene').first()
  for (const step of [8, 9, 10, 11]) {
    await panel.getByRole('button', { name: `第 4 页 · 第 ${step + 1} 步`, exact: true }).click()
    await expect(scene).toBeInViewport({ ratio: .5 })
    await expect(scene).toHaveAttribute('data-status', 'ready')
    await expect(scene).toHaveAttribute('data-position', String((step - 7) * 1000))
  }
  await page.locator('.pmw-navigation button').first().click()
  for (const width of [1440, 390]) for (const scheme of ['light', 'dark'] as const) {
    await page.setViewportSize({ width, height: 1000 })
    await page.emulateMedia({ colorScheme: scheme })
    if (width < 768 && await page.locator('.pmw-navigation').isVisible())
      await page.locator('.pmw-navigation button').first().click()
    if (!await panel.isVisible())
      await page.locator('.pmw-toolbar').getByRole('button', { name: '步骤讲解', exact: true }).click()
    await panel.getByRole('button', { name: '第 4 页 · 第 9 步', exact: true }).click()
    if (width < 768) await panel.getByRole('button', { name: '关闭', exact: true }).click()
    await expect(scene).toBeInViewport({ ratio: .5 })
    await page.screenshot({ path: test.info().outputPath(`late-step-${width}-${scheme}.png`) })
  }
  expect(errors).toEqual([])
})
