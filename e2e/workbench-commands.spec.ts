import { expect, test } from '@playwright/test'
import { startStudio } from './fixtures/workbench/studio.ts'
import type { Studio } from './fixtures/workbench/studio.ts'
import { selectPreview, splitPreview } from './fixtures/workbench/ui.ts'

test.describe.configure({ mode: 'serial', timeout: 180_000 })
test.use({ locale: 'zh-CN', actionTimeout: 30_000 })

let studio: Studio

test.beforeAll(async () => {
  studio = await startStudio({ port: 6963 + Number(process.env.PRESMIUM_E2E_STUDIO_PORT_OFFSET ?? 0), prefix: 'workbench-commands' })
})
test.afterAll(async () => { await studio?.close() })

test('Quick Open locates workspace code while a lecture is open and keeps the unsaved lecture', async ({ page }) => {
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '分词入门' }).locator('.pmw-home__open').click()
  await page.keyboard.press('Control+p')
  const search = page.getByRole('combobox', { name: '搜索文件、文档或命令' })
  await expect(search).toBeFocused()
  await search.fill('lectures/intro/lecture.md')
  await expect(page.getByRole('option', { name: 'lectures/intro/lecture.md', exact: true })).toBeVisible()
  await search.press('Enter')
  const editor = page.locator('.pmw-source__editor .cm-content')
  await expect(editor).toContainText('一份讲分词的讲义')
  await editor.click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.type('\n尚未保存的课堂笔记')
  await expect(page.getByRole('img', { name: '未保存' })).toHaveCount(1)
  await page.keyboard.press('Meta+p')
  await search.fill('examples/sample-repo/src/bpe.py:2')
  await expect(page.getByRole('option', { name: 'examples/sample-repo/src/bpe.py', exact: true })).toBeVisible()
  await expect(page.getByRole('option', { name: 'presmium.workspace.yaml', exact: true })).toBeHidden()
  await search.press('Enter')
  await expect(page.locator('.pmw-source__editor')).toHaveAttribute('data-path', 'examples/sample-repo/src/bpe.py')
  await expect(page.locator('[data-status="line"]')).toHaveText('第 2 行')
  await splitPreview(page)
  await expect(page.locator('.pmw-preview__frame')).toHaveAttribute('title', '分词入门 的预览')
  await page.getByRole('tab', { name: 'lecture.md' }).click()
  await expect(editor).toContainText('尚未保存的课堂笔记')
  await editor.click()
  await page.keyboard.press('Control+p')
  await search.press('Escape')
  await expect(page.getByRole('dialog', { name: '快速打开文件（Ctrl/Cmd+P）' })).toBeHidden()
  await expect(editor).toContainText('尚未保存的课堂笔记')
  await expect(editor).toBeFocused()
  await page.keyboard.type('，继续讲解')
  await expect(editor).toContainText('继续讲解')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.keyboard.press('Control+p')
  await search.fill('Second lecture')
  await expect(page.getByRole('option', { name: 'Second lecture lectures/second' })).toBeVisible()
  await search.press('Enter')
  const unsaved = page.getByRole('dialog', { name: '保存未完成的修改？' })
  await expect(unsaved).toBeVisible()
  await unsaved.getByRole('button', { name: '取消', exact: true }).click()
  await expect(editor).toContainText('尚未保存的课堂笔记')
  await page.keyboard.press('Control+p')
  await search.fill('Second lecture')
  await expect(page.getByRole('option', { name: 'Second lecture lectures/second' })).toBeVisible()
  await search.press('Enter')
  await unsaved.getByRole('button', { name: '不保存', exact: true }).click()
  await expect(page.locator('.pmw-preview__frame')).toHaveAttribute('title', 'Second lecture 的预览')
  await expect(page.locator('.pmw-frame')).toHaveAttribute('data-pane', 'preview')
})

test('commands change the lecture layout and Quick Open also works from the launcher', async ({ page }) => {
  await studio.open(page)
  await page.keyboard.press('Control+p')
  const search = page.getByRole('combobox', { name: '搜索文件、文档或命令' })
  await search.fill('分词入门')
  await expect(page.getByRole('option', { name: '分词入门 lectures/intro', exact: true })).toBeVisible()
  await search.press('Enter')
  await expect(page.locator('.pmw-preview__frame')).toHaveAttribute('title', '分词入门 的预览')
  await page.keyboard.press('Control+p')
  await search.fill('lectures/intro/lecture.md')
  await expect(page.getByRole('option', { name: 'lectures/intro/lecture.md', exact: true })).toBeVisible()
  await search.press('Enter')
  const editor = page.locator('.pmw-source__editor .cm-content')
  await expect(editor).toContainText('一份讲分词的讲义')
  await selectPreview(page)
  await page.keyboard.press('Control+Shift+p')
  await expect(page.getByRole('dialog', { name: '命令面板' })).toBeVisible()
  await expect(search).toHaveValue('>')
  await search.fill('>显示源码')
  await search.press('Enter')
  await expect(editor).toBeVisible()
  await expect(page.locator('.pmw-doc__preview')).toBeHidden()
  await page.keyboard.press('Control+Shift+p')
  await search.fill('>显示预览')
  await search.press('Enter')
  await expect(page.locator('.pmw-preview__frame')).toBeVisible()
  await expect(editor).toBeHidden()
})
