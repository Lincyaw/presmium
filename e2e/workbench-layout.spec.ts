import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { startStudio } from './fixtures/workbench/studio.ts'
import type { Studio } from './fixtures/workbench/studio.ts'

test.describe.configure({ mode: 'serial', timeout: 180_000 })
test.use({ locale: 'zh-CN', actionTimeout: 30_000 })
let studio: Studio
test.beforeAll(async () => {
  studio = await startStudio({ port: 6965 + Number(process.env.PRESMIUM_E2E_STUDIO_PORT_OFFSET ?? 0), prefix: 'editor-groups' })
})
test.afterAll(async () => studio?.close())

const editor = (page: Page) => page.locator('.pmw-source__editor .cm-content')
async function start(page: Page) {
  await studio.open(page)
  await page.locator('.pmw-home__card').filter({ hasText: '分词入门' }).locator('.pmw-home__open').click()
  await expect(page.locator('.pmw-preview')).toHaveAttribute('data-ready', 'true', { timeout: 60_000 })
}
async function openSource(page: Page) {
  await page.keyboard.press('Control+p')
  const search = page.getByRole('combobox', { name: '搜索文件、文档或命令' })
  await search.fill('lectures/intro/lecture.md')
  await search.press('Enter')
  await expect(editor(page)).toBeVisible()
}

test('resources share one tab strip; explicit splitting and closing previews preserve drafts and undo', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 900 })
  await start(page)
  await expect(page.getByRole('tab', { name: '文档预览', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(page.locator('.pmw-document').getByRole('radio')).toHaveCount(0)
  const frame = await page.locator('.pmw-preview__frame').elementHandle()
  if (!frame) throw new Error('preview missing')
  await openSource(page)
  await expect(page.locator('.pmw-preview')).toBeHidden()
  await expect(page.locator('.pmw-editor-group__bar:visible')).toHaveCount(1)
  await expect(page.getByRole('button', { name: '查看问题', exact: true })).toBeVisible()
  const sourceTab = page.getByRole('tab', { name: /lecture\.md/ })
  const previewTab = page.getByRole('tab', { name: '文档预览', exact: true })
  await sourceTab.focus()
  await sourceTab.press('ArrowRight')
  await expect(previewTab).toBeFocused()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await previewTab.press('ArrowLeft')
  await expect(sourceTab).toBeFocused()
  await expect(editor(page)).toBeVisible()
  await editor(page).click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\nUnsent classroom draft')
  await page.getByRole('tab', { name: '文档预览', exact: true }).click()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await expect.poll(() => frame.evaluate(element => element.isConnected)).toBe(true)
  await page.getByRole('tab', { name: /lecture\.md/ }).click()
  await expect(editor(page)).toContainText('Unsent classroom draft')
  await editor(page).click()
  await page.keyboard.press('ControlOrMeta+z')
  await expect(editor(page)).not.toContainText('Unsent classroom draft')
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\nKeep this second draft')
  await sourceTab.click()
  await sourceTab.press('ControlOrMeta+s')
  await expect(page.locator('.pmw-editor-group__tab:visible .pmw-source__dot')).toBeHidden()
  await editor(page).click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\nUnsent after tab save')
  await page.getByRole('button', { name: '在侧边打开预览', exact: true }).click()
  await expect(page.locator('.pmw-source')).toBeVisible()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await expect(page.locator('.pmw-editor-group__bar:visible')).toHaveCount(2)
  await expect(page.locator('.pmw-source').getByRole('tab', { name: '文档预览' })).toHaveCount(0)
  await page.getByRole('button', { name: '关闭 文档预览', exact: true }).click()
  await expect(page.locator('.pmw-preview')).toBeHidden()
  await expect(editor(page)).toContainText('Keep this second draft')
  await expect(page.locator('.pmw-home')).toHaveCount(0)
  await page.getByRole('button', { name: '打开预览', exact: true }).click()
  await page.getByRole('menuitem', { name: '文档预览', exact: true }).click()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await page.getByRole('button', { name: '在侧边打开预览', exact: true }).click()
  await page.getByRole('button', { name: '合并编辑组', exact: true }).click()
  await expect(page.locator('.pmw-editor-group__bar:visible')).toHaveCount(1)
  await page.getByRole('tab', { name: /lecture\.md/ }).click()
  await expect(editor(page)).toContainText('Keep this second draft')
  await page.getByRole('button', { name: '在侧边打开预览', exact: true }).click()
  await page.getByRole('button', { name: '关闭 lecture.md', exact: true }).click()
  const unsaved = page.getByRole('dialog', { name: '保存未完成的修改？' })
  await unsaved.getByRole('button', { name: '取消', exact: true }).click()
  await expect(editor(page)).toContainText('Keep this second draft')
  await page.getByRole('button', { name: '关闭 lecture.md', exact: true }).click()
  await unsaved.getByRole('button', { name: '不保存', exact: true }).click()
  await expect(page.locator('.pmw-source')).toBeHidden()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await expect(page.locator('.pmw-editor-group__bar:visible')).toHaveCount(1)
})

test('narrow screens use the same resource tabs and keep drafts across chat and preview', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await start(page)
  await openSource(page)
  await editor(page).click()
  await page.keyboard.press('ControlOrMeta+End')
  await page.keyboard.insertText('\nNarrow classroom draft')
  await expect(page.getByRole('button', { name: '在侧边打开预览', exact: true })).toHaveCount(0)
  await page.getByRole('tab', { name: '文档预览', exact: true }).click()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await page.locator('[data-activity="sessions"]').click()
  await page.locator('[data-activity="preview"]').click()
  await expect(page.locator('.pmw-preview')).toBeVisible()
  await page.getByRole('tab', { name: /lecture\.md/ }).click()
  await expect(editor(page)).toContainText('Narrow classroom draft')
  await expect(page.locator('.pmw-frame')).toHaveAttribute('data-view', 'source')
  // The single resource bar belongs to the stable main group, above both mounted contents.
  const visibleBar = await page.locator('.pmw-editor-group__bar:visible').boundingBox()
  expect(visibleBar!.width).toBeLessThanOrEqual(390)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.getByRole('button', { name: '在侧边打开预览', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(editor(page)).toBeVisible()
  await page.locator('[data-activity="sessions"]').click()
  await page.locator('[data-activity="preview"]').click()
  await expect(editor(page)).toContainText('Narrow classroom draft')
})
