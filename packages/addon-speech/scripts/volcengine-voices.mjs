#!/usr/bin/env node
// Writes src/node/engines/volcengine-voices.ts: the voices of Volcengine's speech synthesis 2.0, read from the
// voice list in its documentation (docs/6561/1257544), for operators without console credentials.
//   node packages/addon-speech/scripts/volcengine-voices.mjs
import { writeFileSync } from 'node:fs'

const SOURCE = 'https://www.volcengine.com/api/doc/getDocDetail?LibraryID=6561&DocumentID=1257544&type=online'
const PAGE = 'https://www.volcengine.com/docs/6561/1257544'
const TARGET = new URL('../src/node/engines/volcengine-voices.ts', import.meta.url)

// The language cell's words, longest first so 英式英语 is not read as 英语.
const LANGUAGES = [
  ['英式英语', 'en-GB'], ['澳洲英语', 'en-AU'], ['美式英语', 'en-US'], ['英语', 'en-US'], ['英文', 'en-US'],
  ['中文', 'zh-CN'], ['日语', 'ja-JP'], ['日文', 'ja-JP'], ['韩语', 'ko-KR'], ['印尼', 'id-ID'],
  ['墨西哥西班牙语', 'es-MX'], ['墨西哥西语', 'es-MX'], ['西班牙西语', 'es-ES'], ['西班牙语', 'es-ES'],
  ['巴西葡萄牙语', 'pt-BR'], ['葡萄牙语', 'pt-PT'], ['泰语', 'th-TH'], ['越南语', 'vi-VN'], ['俄罗斯语', 'ru-RU'], ['俄语', 'ru-RU'],
  ['马来语', 'ms-MY'], ['法语', 'fr-FR'], ['意大利语', 'it-IT'], ['阿拉伯语', 'ar-SA'], ['菲律宾语', 'fil-PH'], ['德语', 'de-DE'],
  ['土耳其语', 'tr-TR'], ['波兰语', 'pl-PL'], ['瑞典语', 'sv-SE'],
]
// When the cell names no language: the id's language part (zh_…, ICL_uranus_en_…).
const PREFIXES = { zh: 'zh-CN', en: 'en-US', ja: 'ja-JP', ko: 'ko-KR', id: 'id-ID', vi: 'vi-VN', es: 'es-MX', pt: 'pt-BR', th: 'th-TH', ru: 'ru-RU', ms: 'ms-MY', fr: 'fr-FR', it: 'it-IT', ar: 'ar-SA', de: 'de-DE' }
const VOICE = /^(?:ICL_)?[A-Za-z][A-Za-z0-9_-]*_(?:bigtts|tob)$/
// The list escapes Markdown characters in ids and names (tl_male_jonathan\-palad_uranus_bigtts).
const unescape = text => text.replace(/\\([\\`*_{}[\]()#+\-.!|])/g, '$1')

function languages(cell, id) {
  let rest = cell.replace(/方言[:：].*$/, '')
  const found = []
  for (const [word, tag] of LANGUAGES) {
    if (!rest.includes(word)) continue
    rest = rest.replaceAll(word, '')
    if (!found.includes(tag)) found.push(tag)
  }
  if (!found.length) {
    const prefix = PREFIXES[id.replace(/^ICL_uranus_/, '').split('_')[0]]
    if (prefix) found.push(prefix)
  }
  // The list says its Chinese voices speak English too.
  if (found.includes('zh-CN') && !found.some(tag => tag.startsWith('en-'))) found.push('en-US')
  return found
}

const answer = await fetch(SOURCE, { headers: { 'User-Agent': 'Mozilla/5.0' } })
if (!answer.ok) throw new Error(`${SOURCE} answered ${answer.status}`)
const markdown = (await answer.json()).Result?.MDContent
if (typeof markdown !== 'string') throw new Error('the voice list has no content')

const voices = new Map()
let inModel = false
for (const line of markdown.split('\n')) {
  if (line.startsWith('## ')) { inModel = line.includes('豆包语音合成模型2.0'); continue }
  if (!inModel || !line.startsWith('|')) continue
  const cells = line.split('|').map(cell => unescape(cell.replace(/\*\*/g, '').replace(/<br\s*\/?>/g, ' ')).trim())
  const at = cells.findIndex(cell => VOICE.test(cell))
  if (at < 1) continue
  const id = cells[at]
  if (!voices.has(id)) voices.set(id, { id, label: cells[at - 1] || id, lang: languages(cells[at + 1] ?? '', id) })
}
if (voices.size < 100) throw new Error(`only ${voices.size} voices were read: the list's layout has changed`)

const quote = value => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const rows = [...voices.values()].map(voice => `  { id: ${quote(voice.id)}, label: ${quote(voice.label)}, lang: [${voice.lang.map(quote).join(', ')}] },`)
writeFileSync(TARGET, `import type { VoiceInfo } from '@lincyaw/kernel'

// The voices of Volcengine's speech synthesis 2.0 (seed-tts-2.0), for operators without console credentials.
// Generated by scripts/volcengine-voices.mjs from ${PAGE}; do not edit.
export const VOLCENGINE_VOICES: VoiceInfo[] = [
${rows.join('\n')}
]
`)
console.log(`${voices.size} voices → ${TARGET.pathname}`)
