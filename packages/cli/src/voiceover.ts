import { randomBytes } from 'node:crypto'
import { relative } from 'node:path'
import { changeDocumentVoice, errorMessage, SPEECH, speechEngineId, speechFailureCode, VOICEOVER_EXECUTION } from '@lincyaw/kernel'
import type { SpeechCachePrune, SpeechEngineInfo, SpeechService, SpeechVoice, TeachingDocument, VoiceoverExecution, VoiceoverRunResult, VoiceoverSentence, VoiceoverSentences, VoiceScope } from '@lincyaw/kernel'
import { Compiler } from '@lincyaw/compiler'
import type { Compilation } from '@lincyaw/compiler'
import { readDocumentFile, saveDocumentFile } from './document-file.ts'
import type { CliMessages } from './messages.ts'

export interface VoiceoverOptions {
  entry: string
  /** Make this the document's default voice first. */
  voice?: SpeechVoice
  /** Consent to the paid generation and to the changes; without it the command only reports. */
  yes: boolean
  prune: boolean
  json: boolean
  bundled: string
}

/** A refusal or failure the author can act on: exit code 1, unlike a usage or internal error. */
export class VoiceoverFailure extends Error {}

/** Sentences that are not generated by design: their step is silent or uses a recording. */
const BY_DESIGN = new Set(['voice-none', 'recording-unavailable'])

interface Tally {
  total: number
  cached: number
  missing: VoiceoverSentence[]
  skipped: number
  blocked: VoiceoverSentence[]
  characters: number
}

function tally(sentences: VoiceoverSentence[]): Tally {
  const missing = sentences.filter(sentence => !sentence.cached && !sentence.reason)
  return {
    total: sentences.length,
    cached: sentences.filter(sentence => sentence.cached).length,
    missing,
    skipped: sentences.filter(sentence => sentence.reason && BY_DESIGN.has(sentence.reason)).length,
    blocked: sentences.filter(sentence => !sentence.cached && sentence.reason && !BY_DESIGN.has(sentence.reason)),
    characters: missing.reduce((sum, sentence) => sum + [...sentence.text].length, 0),
  }
}

export function voiceLabel(voice: SpeechVoice): string {
  return `${voice.engine ? `${voice.engine}:` : ''}${voice.voice}${voice.rate !== undefined && voice.rate !== 1 ? ` ×${voice.rate}` : ''}${voice.style ? ` (${voice.style})` : ''}`
}

const sameVoice = (a: SpeechVoice, b: SpeechVoice) => a.voice === b.voice && speechEngineId(a.engine ?? '') === speechEngineId(b.engine ?? '')

/** The document's default voice, or why it has none. */
function defaultVoice(document: TeachingDocument): SpeechVoice | 'none' | undefined {
  const source = document.production.defaults.voiceSource
  return source?.type === 'tts' ? source.voice : source?.type === 'none' ? 'none' : undefined
}

function services(compilation: Compilation, t: CliMessages): { execution: VoiceoverExecution & Required<Pick<VoiceoverExecution, 'sentences'>>, speech?: SpeechService } {
  const execution = compilation.service(VOICEOVER_EXECUTION)
  if (!execution?.sentences) throw new VoiceoverFailure(t.voiceoverUnavailable)
  const speech = compilation.service(SPEECH)
  return { execution: execution as VoiceoverExecution & Required<Pick<VoiceoverExecution, 'sentences'>>, ...speech ? { speech } : {} }
}

/** Where a sentence is, as the author numbers pages and steps. */
function place(compilation: Compilation, sentence: VoiceoverSentence, t: CliMessages): string {
  const index = compilation.doc.sections.findIndex(section => section.id === sentence.section)
  return t.voiceoverPlace(index + 1, sentence.step + 1)
}

function reasonText(reason: string, t: CliMessages): string {
  const code = speechFailureCode(reason) ?? reason
  return t.voiceoverReasons[code] ?? t.voiceoverReasonOther(reason.length > 80 ? `${reason.slice(0, 80)}…` : reason)
}

const megabytes = (bytes: number) => (bytes / 1048576).toFixed(1)

interface Engines { list: SpeechEngineInfo[], fallback?: string }

/** The voice services the sentences use, with whether each is configured and runs on this machine. */
function usedServices(sentences: VoiceoverSentence[], engines: Engines): { id: string, info?: SpeechEngineInfo }[] {
  const ids = [...new Set(sentences.flatMap(sentence => sentence.request ? [speechEngineId(sentence.request.engine ?? engines.fallback ?? '')] : []))].filter(Boolean)
  return ids.map(id => ({ id, ...engines.list.find(engine => engine.id === id) ? { info: engines.list.find(engine => engine.id === id)! } : {} }))
}

function voicesOf(sentences: VoiceoverSentence[], engines: Engines): string[] {
  return [...new Set(sentences.flatMap(sentence => sentence.request ? [voiceLabel({ ...sentence.request, engine: sentence.request.engine ?? engines.fallback })] : []))]
}

/** On a terminal one line that updates; elsewhere a line at the start, at most every five seconds, and at the end. */
class Progress {
  readonly #tty = Boolean(process.stderr.isTTY)
  #last = ''
  #at = 0
  show(text: string, final = false): void {
    if (text === this.#last) return
    if (!this.#tty && this.#last && !final && Date.now() - this.#at < 5000) return
    this.#last = text
    this.#at = Date.now()
    process.stderr.write(this.#tty ? `\r\x1b[2K${text}` : `${text}\n`)
  }
  end(): void {
    if (this.#tty && this.#last) process.stderr.write('\n')
    this.#last = ''
  }
}

/**
 * `presmium voiceover`: what generating the document's voiceover would do, and with consent doing it in this process
 * through the plugins' voiceover execution, the one the workspace service runs for Presmium Studio.
 */
export async function runVoiceover(options: VoiceoverOptions, t: CliMessages): Promise<number> {
  const controller = new AbortController()
  const interrupt = () => controller.abort()
  process.once('SIGINT', interrupt)
  try {
    return await voiceover(options, t, controller.signal)
  } finally {
    process.off('SIGINT', interrupt)
  }
}

async function voiceover(options: VoiceoverOptions, t: CliMessages, signal: AbortSignal): Promise<number> {
  const say = (line: string) => { if (!options.json) process.stdout.write(`${line}\n`) }
  const file = readDocumentFile(options.entry)
  const compiler = new Compiler(options.entry, { bundled: options.bundled })
  let compilation = await compiler.compile({ signal })
  let { execution, speech } = services(compilation, t)
  const engines: Engines = { list: await speech?.engines().catch(() => []) ?? [] }
  const fallback = await speech?.defaultSynthesisEngine?.().catch(() => undefined)
  if (fallback) engines.fallback = fallback

  const before = defaultVoice(file.document)
  const changesVoice = options.voice !== undefined && !(typeof before === 'object' && sameVoice(before, options.voice))
  const planned = changesVoice ? changeDocumentVoice(file.document, { kind: 'document' }, { type: 'tts', voice: options.voice! }) : file.document
  let listing: VoiceoverSentences = await execution.sentences(changesVoice ? { defaultVoice: options.voice! } : {}, signal)
  let counts = tally(listing.sentences)

  const json: Record<string, unknown> = { document: compilation.deckDir }
  say(`${t.voiceoverLabels.document}  ${relative(process.cwd(), compilation.deckDir) || '.'}`)
  const now = defaultVoice(planned)
  const shown = typeof now === 'object' ? voiceLabel(now) : now === 'none' ? t.voiceoverNoVoice : t.voiceoverUnset
  say(`${t.voiceoverLabels.voice}  ${changesVoice ? t.voiceoverVoiceChange(shown, typeof before === 'object' ? voiceLabel(before) : before === 'none' ? t.voiceoverNoVoice : t.voiceoverUnset) : t.voiceoverVoiceDefault(shown)}`)
  json.voice = { default: typeof now === 'object' ? now : null, changed: changesVoice }
  const used = usedServices(counts.missing.length ? counts.missing : listing.sentences, engines)
  for (const { id, info } of used) say(`${t.voiceoverLabels.service}  ${info ? t.voiceoverService(id, info.provider, info.local) : t.voiceoverServiceMissing(id)}`)
  json.services = used.map(({ id, info }) => ({ id, configured: Boolean(info), ...info ? { provider: info.provider, local: info.local } : {} }))
  say(`${t.voiceoverLabels.sentences}  ${t.voiceoverCounts(counts.total, counts.cached, counts.missing.length, counts.skipped, counts.blocked.length)}`)
  const sentencesJson = (value: Tally) => ({ total: value.total, cached: value.cached, missing: value.missing.length, characters: value.characters, skipped: value.skipped, blocked: value.blocked.map(sentence => ({ section: sentence.section, step: sentence.step, ...sentence.stepId ? { stepId: sentence.stepId } : {}, reason: sentence.reason })) })
  json.sentences = sentencesJson(counts)
  const cloud = used.filter(({ info }) => info && !info.local).map(({ info }) => info!.provider)
  if (counts.missing.length) {
    say(`${t.voiceoverLabels.missing}  ${t.voiceoverMissing(counts.missing.length, counts.characters, voicesOf(counts.missing, engines))}`)
    say(cloud.length ? t.voiceoverCharges([...new Set(cloud)]) : t.voiceoverLocal)
  }
  const reasons = new Map<string, VoiceoverSentence[]>()
  for (const sentence of counts.blocked) reasons.set(sentence.reason!, [...reasons.get(sentence.reason!) ?? [], sentence])
  for (const [reason, group] of reasons) say(`${t.voiceoverLabels.blocked}  ${t.voiceoverBlocked(group.length, reasonText(reason, t), group.slice(0, 3).map(sentence => place(compilation, sentence, t)), group.length > 3)}`)

  let prune: SpeechCachePrune | undefined
  const pruneCache = async (value: VoiceoverSentences, remove: boolean) => {
    if (compilation.doc.diagnostics.some(finding => finding.severity === 'error')) throw new VoiceoverFailure(t.voiceoverPruneErrors)
    if (!speech?.pruneCache) throw new VoiceoverFailure(t.voiceoverPruneUnavailable)
    try {
      return await speech.pruneCache(value.sentences.flatMap(sentence => sentence.request ? [sentence.request] : []), { remove, signal })
    } catch (error) {
      if (errorMessage(error) === 'speech-prune-engine-unknown') throw new VoiceoverFailure(t.voiceoverPruneEngineUnknown)
      throw error
    }
  }
  if (options.prune) {
    prune = await pruneCache(listing, false)
    const bytes = prune.unused.reduce((sum, entry) => sum + entry.bytes, 0)
    say(`${t.voiceoverLabels.prune}  ${t.voiceoverPruneWould(prune.unused.length, megabytes(bytes), prune.kept)}`)
    json.prune = { unused: prune.unused.length, bytes, kept: prune.kept, removed: false }
  }

  const work = counts.missing.length > 0 || changesVoice || Boolean(prune?.unused.length)
  if (!options.yes) {
    say(work ? t.voiceoverDryRun : counts.blocked.length ? t.voiceoverNothingElse : t.voiceoverNothing)
    if (options.json) process.stdout.write(`${JSON.stringify({ ...json, yes: false }, null, 2)}\n`)
    return 0
  }

  if (changesVoice) {
    const refused = counts.blocked.find(sentence => sentence.request && sameVoice(sentence.request, options.voice!))
    if (refused) throw new VoiceoverFailure(t.voiceoverVoiceRefused(voiceLabel(options.voice!), reasonText(refused.reason!, t)))
    saveDocumentFile(file, planned)
    say(t.voiceoverVoiceSaved(voiceLabel(options.voice!)))
    compilation = await compiler.compile({ signal })
    ;({ execution, speech } = services(compilation, t))
    listing = await execution.sentences({}, signal)
    counts = tally(listing.sentences)
  }

  let result: VoiceoverRunResult | undefined
  let after = counts
  if (counts.missing.length) {
    const intent = randomBytes(18).toString('base64url')
    // By step when every missing sentence has one, so that only the steps with missing audio are gone through.
    const targets = [...new Map(counts.missing.flatMap(sentence => sentence.target ? [[JSON.stringify(sentence.target), sentence.target] as const] : [])).values()]
    const scope: VoiceScope = counts.missing.every(sentence => sentence.target) ? { kind: 'steps', targets } : { kind: 'document' }
    const prepared = await execution.prepare({ intent, source: listing.source, revision: listing.revision, scope }, signal)
    const progress = new Progress()
    try {
      progress.show(t.voiceoverGenerating(0, prepared.total))
      result = await prepared.run(signal, value => progress.show(t.voiceoverGenerating(value.completed + value.failed, prepared.total), value.completed + value.failed === prepared.total))
    } finally {
      progress.end()
      prepared.dispose()
    }
    // Read the cache again, also after a cancel, to report what was really made; a changed document can't be read.
    if (result.state !== 'stale') {
      try {
        listing = await execution.sentences({}, signal.aborted ? new AbortController().signal : signal)
        after = tally(listing.sentences)
      } catch (error) {
        if (!signal.aborted) throw error
      }
    }
    const generated = Math.max(0, after.cached - counts.cached)
    say(result.state === 'cancelled' ? t.voiceoverCancelled(generated) : result.state === 'stale' ? t.voiceoverStale(generated) : t.voiceoverGenerated(generated))
    if (result.error && result.state !== 'cancelled') say(t.voiceoverRunError(reasonText(result.error, t)))
    json.generation = { state: result.state, generated, ...result.error ? { error: result.error } : {} }
  }

  if (options.prune && !signal.aborted && result?.state !== 'stale') {
    prune = await pruneCache(listing, true)
    const bytes = prune.unused.reduce((sum, entry) => sum + entry.bytes, 0)
    say(t.voiceoverPruned(prune.unused.length, megabytes(bytes)))
    json.prune = { unused: prune.unused.length, bytes, kept: prune.kept, removed: true }
  }

  const left = after.missing.length + after.blocked.length
  if (left) say(t.voiceoverLeft(after.missing.length, after.blocked.length))
  json.remaining = sentencesJson(after)
  if (options.json) process.stdout.write(`${JSON.stringify({ ...json, yes: true }, null, 2)}\n`)
  return left || (result && result.state !== 'done' && result.state !== 'failed') ? 1 : 0
}
