CREATE TABLE cloud_environments (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES spaces(id),
  user_id uuid NOT NULL REFERENCES users(id),
  billing_account_id uuid NOT NULL REFERENCES billing_accounts(id),
  profile_id text NOT NULL,
  name text NOT NULL,
  desired_state text NOT NULL DEFAULT 'stopped' CHECK (desired_state IN ('running','stopped')),
  state text NOT NULL DEFAULT 'stopped' CHECK (state IN ('stopped','starting','running','stopping','failed')),
  generation integer NOT NULL DEFAULT 0,
  container_id text,
  credential text NOT NULL,
  reservation_id uuid,
  start_operation_id text,
  started_at timestamptz,
  stopped_at timestamptz,
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  run_deadline timestamptz,
  lease_owner text,
  lease_until timestamptz,
  error_code text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX cloud_environments_owner ON cloud_environments(workspace_id,user_id,created_at);
CREATE INDEX cloud_environments_reconcile ON cloud_environments(state,lease_until);

CREATE TABLE cloud_runtime_jobs (
  id uuid PRIMARY KEY,
  workspace_id uuid NOT NULL REFERENCES spaces(id),
  user_id uuid NOT NULL REFERENCES users(id),
  billing_account_id uuid NOT NULL REFERENCES billing_accounts(id),
  profile_id text NOT NULL,
  operation_id text NOT NULL,
  input_digest text NOT NULL,
  input jsonb NOT NULL,
  kind text NOT NULL CHECK (kind IN ('compile','export')),
  state text NOT NULL DEFAULT 'queued' CHECK (state IN ('queued','starting','running','publishing','succeeded','failed','cancelled')),
  cancel_requested boolean NOT NULL DEFAULT false,
  reservation_id uuid NOT NULL,
  generation integer NOT NULL DEFAULT 0,
  container_id text,
  started_at timestamptz,
  finished_at timestamptz,
  lease_owner text,
  lease_until timestamptz,
  error_code text,
  output jsonb,
  log text,
  settled boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (billing_account_id,operation_id)
);
CREATE INDEX cloud_runtime_jobs_claim ON cloud_runtime_jobs(state,lease_until,created_at);
