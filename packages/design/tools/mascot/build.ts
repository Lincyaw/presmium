// Renders every action's key poses into two sprite sheets (the black cat for light backgrounds, the white cat for
// dark ones), one row per action, and writes the timelines beside them. Run with `pnpm --filter @lincyaw/design mascot`.
import { writeFileSync } from 'node:fs'
import { deflateSync, crc32 } from 'node:zlib'
import { render, W, H, PPU, OY, GROUND } from './draw.ts'
import { ACTIONS, TICK_MS } from './poses.ts'

function png(width: number, height: number, rgba: Uint8ClampedArray): Buffer {
  const chunk = (type: string, data: Buffer) => {
    const head = Buffer.alloc(8); head.writeUInt32BE(data.length, 0); head.write(type, 4, 'ascii')
    const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(Buffer.concat([head.subarray(4), data])), 0)
    return Buffer.concat([head, data, crc])
  }
  const ihdr = Buffer.alloc(13)
  ihdr.writeUInt32BE(width, 0); ihdr.writeUInt32BE(height, 4); ihdr[8] = 8; ihdr[9] = 6
  const raw = Buffer.alloc((width * 4 + 1) * height)
  for (let y = 0; y < height; y++) Buffer.from(rgba.buffer, rgba.byteOffset + y * width * 4, width * 4).copy(raw, y * (width * 4 + 1) + 1)
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))])
}

const names = Object.keys(ACTIONS)
const cols = Math.max(...names.map(n => ACTIONS[n]!.poses.length))
const SW = cols * W, SH = names.length * H
const sheets = { dark: new Uint8ClampedArray(SW * SH * 4), light: new Uint8ClampedArray(SW * SH * 4) }
names.forEach((name, row) => ACTIONS[name]!.poses.forEach((P, col) => {
  for (const [key, light] of [['dark', false], ['light', true]] as const) {
    const frame = render(P, light)
    for (let y = 0; y < H; y++) sheets[key].set(frame.subarray(y * W * 4, (y + 1) * W * 4), ((row * H + y) * SW + col * W) * 4)
  }
}))
const out = new URL('../../src/assets/mascot/', import.meta.url)
writeFileSync(new URL('cat.png', out), png(SW, SH, sheets.dark))
writeFileSync(new URL('cat-light.png', out), png(SW, SH, sheets.light))
const sheet = {
  frame: [W, H], columns: cols, rows: names.length, tickMs: TICK_MS,
  /** Where the ground line is in a frame, in pixels from its top, and pixels per drawing unit. */
  ground: (GROUND - OY) * PPU, unit: PPU,
  actions: Object.fromEntries(names.map((n, row) => [n, { row, timeline: ACTIONS[n]!.timeline }])),
}
writeFileSync(new URL('sheet.ts', out), `// Generated by tools/mascot/build.ts from the key poses in tools/mascot/poses.ts; do not edit.\nexport const SHEET = ${JSON.stringify(sheet)} as const\n`)
console.log(`${names.length} actions, ${names.reduce((s, n) => s + ACTIONS[n]!.poses.length, 0)} poses, sheet ${SW}x${SH}`)
