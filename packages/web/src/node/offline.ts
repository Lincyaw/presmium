import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, sep } from 'node:path'
import { SERVICE_WORKER } from '../domain/index.ts'

/**
 * The service worker precaches every file of the build, so a page loaded once
 * keeps working offline, search index included. Hashed assets are served from
 * the cache first; pages go to the network first and fall back to the cache.
 */
function source(cache: string, urls: string[], base: string): string {
  return `// Generated by presmium-web.
const CACHE = ${JSON.stringify(cache)}
const BASE = ${JSON.stringify(base)}
const URLS = ${JSON.stringify(urls)}

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(URLS)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith('presmium-web-') && key !== CACHE).map(key => caches.delete(key))))
    .then(() => self.clients.claim()))
})

async function cached(request) {
  const url = new URL(request.url)
  url.search = ''
  url.hash = ''
  const path = url.pathname
  const candidates = [url.href]
  if (path.endsWith('/')) candidates.push(url.href + 'index.html')
  else if (!/\\.[^/]+$/.test(path)) candidates.push(url.href + '.html')
  for (const candidate of candidates) {
    const hit = await caches.match(candidate, { cacheName: CACHE })
    if (hit) return hit
  }
  return undefined
}

self.addEventListener('fetch', (event) => {
  const { request } = event
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin || !url.pathname.startsWith(BASE)) return
  if (url.pathname.startsWith(BASE + 'assets/')) {
    event.respondWith(cached(request).then(hit => hit || fetch(request)))
  } else {
    event.respondWith(fetch(request).catch(() => cached(request).then(hit => hit || Response.error())))
  }
})
`
}

function files(dir: string): string[] {
  return readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter(file => statSync(join(dir, file)).isFile() && file !== SERVICE_WORKER)
    .sort()
}

/** Writes the service worker into a finished build; its cache name changes with the build's content. */
export function writeServiceWorker(outDir: string, base: string): void {
  const list = files(outDir)
  const hash = createHash('sha256')
  for (const file of list) hash.update(file).update(readFileSync(join(outDir, file)))
  const urls = list.map(file => encodeURI(base + file.split(sep).join('/')))
  writeFileSync(join(outDir, SERVICE_WORKER), source(`presmium-web-${hash.digest('hex').slice(0, 12)}`, urls, base))
}
