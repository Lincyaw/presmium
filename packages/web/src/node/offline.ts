import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { basename, join, sep } from 'node:path'
import { OFFLINE_REQUESTS } from '@lincyaw/kernel'
import { SERVICE_WORKER, urlPath } from '../domain/index.ts'
import { MEDIA } from './publish.ts'
import { APP_DIR, CODE_DIR } from './site-files.ts'

interface OfflineCache {
  prefix: string
  cache: string
  urls: string[]
  runtimeCache: string
  runtimes: string[]
  runtimeBytes: number
  base: string
  app: string
}

function source({ prefix, cache, urls, runtimeCache, runtimes, runtimeBytes, base, app }: OfflineCache): string {
  return `// Generated by @lincyaw/web.
const CACHE = ${JSON.stringify(cache)}
const PREFIX = ${JSON.stringify(prefix)}
const RUNTIME_CACHE = ${JSON.stringify(runtimeCache)}
const BASE = ${JSON.stringify(base)}
const APP = ${JSON.stringify(app)}
const URLS = ${JSON.stringify(urls)}
const RUNTIMES = ${JSON.stringify(runtimes)}
const RUNTIME_BYTES = ${runtimeBytes}
const RUNTIME_PATHS = new Set(RUNTIMES)

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(URLS)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (event) => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith(PREFIX) && key !== CACHE && key !== RUNTIME_CACHE).map(key => caches.delete(key))))
    .then(() => self.clients.claim()))
})

async function cached(request) {
  const url = new URL(request.url)
  url.search = ''
  url.hash = ''
  const path = url.pathname
  const candidates = [url.href]
  if (path.endsWith('/')) candidates.push(url.href + 'index.html')
  else if (!/\\.[^/]+$/.test(path)) candidates.push(url.href + '.html')
  for (const candidate of candidates) {
    const hit = await caches.match(candidate, { cacheName: CACHE })
    if (hit) return hit
  }
  return undefined
}

/** A runtime file from its cache, else from the network, kept for next time. */
async function runtime(href) {
  const cache = await caches.open(RUNTIME_CACHE)
  const hit = await cache.match(href)
  if (hit) return hit
  const response = await fetch(href)
  if (response.status === 200) await cache.put(href, response.clone())
  return response
}

const runtimeUrls = () => RUNTIMES.map(path => new URL(path, self.location.origin).href)

async function saved() {
  const cache = await caches.open(RUNTIME_CACHE)
  const kept = new Set((await cache.keys()).map(request => request.url))
  return runtimeUrls().every(href => kept.has(href))
}

async function save() {
  for (const href of runtimeUrls()) {
    const response = await runtime(href)
    if (response.status !== 200) throw new Error(href + ': ' + response.status)
  }
}

self.addEventListener('message', (event) => {
  const port = event.ports[0]
  const type = event.data && event.data.type
  if (!port) return
  if (type === ${JSON.stringify(OFFLINE_REQUESTS.runtimes)}) {
    event.waitUntil(saved().then(done => port.postMessage({ bytes: RUNTIME_BYTES, saved: done })))
  } else if (type === ${JSON.stringify(OFFLINE_REQUESTS.save)}) {
    event.waitUntil(save().then(() => port.postMessage({ ok: true }), () => port.postMessage({ ok: false })))
  }
})

self.addEventListener('fetch', (event) => {
  const { request } = event
  const url = new URL(request.url)
  if (request.method !== 'GET' || url.origin !== self.location.origin || !(url.pathname.startsWith(BASE) || url.pathname.startsWith(APP))) return
  if (RUNTIME_PATHS.has(url.pathname)) {
    url.search = ''
    url.hash = ''
    event.respondWith(runtime(url.href))
  } else if (url.pathname.startsWith(APP) || url.pathname.startsWith(BASE + ${JSON.stringify(`${CODE_DIR}/`)})) {
    event.respondWith(cached(request).then(hit => hit || fetch(request)))
  } else {
    event.respondWith(fetch(request).catch(() => cached(request).then(hit => hit || Response.error())))
  }
})
`
}

function fallbackFonts(dir: string, all: string[]): Set<string> {
  const unused = new Set<string>()
  for (const file of all.filter(f => f.endsWith('.css'))) {
    for (const [, face] of readFileSync(join(dir, file), 'utf8').matchAll(/@font-face\s*\{([^}]*)\}/g)) {
      if (!/woff2/.test(face!)) continue
      for (const [, url] of face!.matchAll(/url\(\s*["']?([^"')]+\.(?:woff|ttf))["']?\s*\)/g)) unused.add(url!.split('/').pop()!)
    }
  }
  return unused
}

function files(dir: string): string[] {
  const all = readdirSync(dir, { recursive: true, encoding: 'utf8' })
    .filter(file => statSync(join(dir, file)).isFile() && file !== SERVICE_WORKER)
    .sort()
  const unused = fallbackFonts(dir, all)
  return all.filter(file => !unused.has(file.split(sep).pop()!))
}

const isRuntime = (file: string) => /^(?:pyodide|wasi|presmium\/jax-js)\//.test(file) && !/(?:^|\/)LICENSES?$/.test(file)

/**
 * Writes the document's service worker: it keeps the document's files and the viewer app's (`app`, below the site's
 * path, shared with the site's other documents) for reading offline, and the plugins' run-time files on request.
 */
export function writeServiceWorker(outDir: string, base: string, app: { dir: string, url: string }): void {
  const list = files(outDir).filter(file => !file.startsWith(`${APP_DIR}${sep}`)).map(file => file.split(sep).join('/'))
  const shell = list.filter(file => !isRuntime(file))
  const runtimes = list.filter(isRuntime)
  const hash = (names: string[]) => {
    const digest = createHash('sha256')
    for (const file of names) digest.update(file).update(readFileSync(join(outDir, file)))
    return digest.digest('hex').slice(0, 12)
  }
  const urls = (names: string[]) => names.map(file => file.split('/')).map(parts => base + (parts[0] === MEDIA ? parts.map(encodeURIComponent).join('/') : urlPath(parts.join('/'))))
  const appFiles = files(app.dir).map(file => app.url + urlPath(file.split(sep).join('/')))
  const bytes = runtimes.reduce((sum, file) => sum + statSync(join(outDir, file)).size, 0)
  const scope = createHash('sha256').update(base).digest('hex').slice(0, 16)
  const prefix = `presmium-web-${scope}-`
  writeFileSync(join(outDir, SERVICE_WORKER), source({
    prefix, cache: `${prefix}${hash(shell)}-${basename(app.dir)}`, urls: [...urls(shell), ...appFiles],
    runtimeCache: `${prefix}runtimes-${hash(runtimes)}`, runtimes: urls(runtimes), runtimeBytes: bytes, base, app: app.url,
  }))
}
