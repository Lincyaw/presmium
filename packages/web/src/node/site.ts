const CLIENT_ENTRY = fileURLToPath(new URL('../client/index.ts', import.meta.url))
const PREVIEW_AGENT = fileURLToPath(new URL('../client/preview.ts', import.meta.url))
const SEARCH = createRequire(import.meta.url).resolve('@lincyaw/kernel/reading')
const VITE_PLUGIN = fileURLToPath(new URL('./vite.ts', import.meta.url))
const GENERATED = '// Generated by @lincyaw/web from the IR; do not edit.'
const WEB_DIR = fileURLToPath(new URL('../..', import.meta.url))

export function siteFiles(workDir: string) {
  return {
    root: join(workDir, 'site'),
    ir: join(workDir, 'ir.json'),
    searchDocuments: join(workDir, 'search-documents.json'),
    site: join(workDir, 'site.json'),
    publicDir: join(workDir, 'site', 'public'),
  }
}

export const SRC_EXCLUDE = ['public/**']

export function presmiumRoot(): string {
  const own = realpathSync(WEB_DIR)
  let outermost: string | undefined
  for (let dir = own; dirname(dir) !== dir; dir = dirname(dir)) {
    if (existsSync(join(dir, 'pnpm-workspace.yaml'))) return dir
    if (dir.split(sep).at(-1) === 'node_modules') outermost = dirname(dir)
  }
  return outermost ?? own
}

export function allowed(...dirs: (string | undefined)[]): string[] {
  return [...new Set(dirs.filter((dir): dir is string => Boolean(dir)).map(dir => (existsSync(dir) ? realpathSync(dir) : dir)))]
}

export function write(file: string, content: string | Buffer): void {
  if (existsSync(file) && readFileSync(file).equals(Buffer.from(content))) return
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
}

function copyDir(from: string, to: string): void {
  for (const file of readdirSync(from, { recursive: true, encoding: 'utf8' })) {
    const source = join(from, file)
    const stat = statSync(source)
    if (!stat.isFile()) continue
    const target = join(to, file)
    const copied = existsSync(target) ? statSync(target) : undefined
    if (copied && copied.size === stat.size && Math.abs(copied.mtimeMs - stat.mtimeMs) < 1) continue
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, readFileSync(source))
    utimesSync(target, stat.atime, stat.mtime)
  }
}

export function linkDependencies(root: string): void {
  const require = createRequire(import.meta.url)
  for (const name of ['vitepress', 'vue']) {
    const target = dirname(require.resolve(`${name}/package.json`))
    const link = join(root, 'node_modules', name)
    if (existsSync(link) && readlinkSync(link) === target) continue
    rmSync(link, { force: true })
    mkdirSync(dirname(link), { recursive: true })
    symlinkSync(target, link, 'junction')
  }
}

export function browserPackages(modules: ClientModules): string[] {
  const files = [...modules.plugins, ...modules.viewers.map(({ file }) => file), ...modules.components.values()]
  return [...new Set([WEB_DIR, ...files.flatMap(file => packageOf(file) ?? [])])]
}

export function languageLabel(lang: string): string {
  const primary = lang.split('-')[0]!
  try {
    return new Intl.DisplayNames([lang], { type: 'language' }).of(primary) ?? lang
  } catch {
    return lang
  }
}

export interface SiteLocale {
  lang: string
  label: string
  title: string
  sidebar: ReturnType<typeof sidebar>
  labels: (typeof SITE_LABELS)[keyof typeof SITE_LABELS]
  nav?: NavItem[]
}

export interface SiteData {
  title: string
  sidebar: ReturnType<typeof sidebar>
  form: FormOptions
  label: string
  locales: SiteLocale[]
}

interface Translation {
  lang: string
  doc: IRDocument
  pages: WebPage[]
}

function siteData(doc: IRDocument, options: WebRendererConfig, translations: Translation[], workspace?: WorkspaceOptions): SiteData {
  const form = formOptions(doc.config.presmium, doc.config.renderers)
  return {
    title: doc.meta.title,
    sidebar: sidebar(doc, toPages(doc)),
    form: workspace ? { ...form, slides: Boolean(form.slidesUrl) } : form,
    label: languageLabel(options.lang),
    locales: translations.map(({ lang, doc: translated, pages }) => ({
      lang,
      label: languageLabel(lang),
      title: translated.meta.title,
      sidebar: sidebar(translated, pages, `/${lang}`),
      labels: SITE_LABELS[deckLocale(lang)],
      ...options.shell.nav && workspace ? { nav: relativeNav(options.shell.nav, depthOf(workspace.document) + 1) } : {},
    })),
  }
}

export interface WorkspaceOptions {
  document: string
  home: string
  endpoints: { ir: string, source: string }
  served?: boolean
  allow?: string[]
  neighbours?: { prev?: Neighbour, next?: Neighbour }
  search?: SearchDocument[]
}

export interface DeckPaths {
  deckDir: string
  workspaceRoot: string
}

function depthOf(dir: string): number {
  return dir ? dir.split('/').length : 0
}

function fromPage(link: string, depth: number): string {
  if (!link.startsWith('/') || link.startsWith('//')) return link
  return `${'../'.repeat(depth)}${link.slice(1)}` || './'
}

function relativeNav(items: NavItem[], depth: number): NavItem[] {
  return items.map(item => ({ ...item, ...item.link ? { link: fromPage(item.link, depth) } : {}, ...item.items ? { items: relativeNav(item.items, depth) } : {} }))
}

function neighbourFrom(other: Neighbour | undefined, depth: number): Neighbour | undefined {
  return other && { text: other.text, link: fromPage(`/${other.link}`, depth) }
}

function shellConfig(shell: SiteShell, base: string, image: string | undefined, workspace?: WorkspaceOptions): { site: Record<string, unknown>, ogTitle: boolean } {
  const site: Record<string, unknown> = {}
  const themeConfig: Record<string, unknown> = {}
  if (shell.nav) themeConfig.nav = workspace ? relativeNav(shell.nav, depthOf(workspace.document)) : shell.nav
  if (shell.footer) themeConfig.footer = shell.footer
  const head: unknown[] = []
  if (shell.head) {
    head.push(['meta', { property: 'og:type', content: 'website' }])
    if (shell.head.description) {
      site.description = shell.head.description
      head.push(['meta', { property: 'og:description', content: shell.head.description }])
    }
    if (image) head.push(['meta', { property: 'og:image', content: image }])
  }
  if (shell.sitemap && !workspace) site.sitemap = { hostname: `${shell.sitemap.hostname}${base}` }
  return { site: { ...site, head, themeConfig }, ogTitle: Boolean(shell.head) }
}

export const OG_TITLE = `site.transformHead = ({ title }) => [['meta', { property: 'og:title', content: title }]]\n`

function config(options: WebRendererConfig, files: ReturnType<typeof siteFiles>, modules: ClientModules, deck: DeckPaths, workspace: WorkspaceOptions | undefined, image: string | undefined, optimize: { include: string[], exclude: string[] }, preview: SiteInput['preview']): string {
  const labels = SITE_LABELS[deckLocale(options.lang)]
  const shell = shellConfig(options.shell, options.base, image, workspace)
  const site = {
    lang: options.lang,
    base: options.base,
    cleanUrls: false,
    ignoreDeadLinks: true,
    srcExclude: SRC_EXCLUDE,
    ...shell.site,
    themeConfig: { ...labels.themeConfig, ...shell.site.themeConfig as object },
  }
  const imports = [
    ...modules.vite.map((file, i) => `import vite${i} from ${JSON.stringify(file)}\n`),
    ...modules.nodeVite.map(({ file }, i) => `import node${i} from ${JSON.stringify(file)}\n`),
  ].join('')
  const nodePlugins = modules.nodeVite.map(({ config: options }, i) =>
    `...(node${i}.vitePlugins?.({ ...deck, config: ${JSON.stringify(options)} }) ?? [])`)
  const server = options.server ? `
site.themeConfig.presmium.server = true
site.vite.server = { proxy: { ${JSON.stringify(SERVER_PROXY)}: { target: ${JSON.stringify(options.server)}, ws: true } }, fs: { allow: ${JSON.stringify(allowed(files.root, deck.deckDir, deck.workspaceRoot, presmiumRoot()))} } }
` : ''
  const inWorkspace = workspace ? `
Object.assign(site.themeConfig.presmium, ${JSON.stringify({ document: workspace.document, home: workspace.home, ir: workspace.endpoints.ir, ...workspace.served ? { server: true } : {} })})
${workspace.served ? `site.vite.server = { fs: { allow: ${JSON.stringify(workspace.allow ?? [])} } }
` : ''}` : ''
  const framed = preview ? `site.vite.plugins.push(presmiumFrame(${JSON.stringify(previewFrameAncestors(preview.origins))}))
` : ''
  return `${GENERATED}
import { readFileSync } from 'node:fs'
import { tokenize } from ${JSON.stringify(SEARCH)}
import { presmiumFrame, presmiumIR } from ${JSON.stringify(VITE_PLUGIN)}
${imports}
const site = ${JSON.stringify(site, null, 2)}

// Read when the config loads, so this file stays the same while the IR changes.
const data = JSON.parse(readFileSync(${JSON.stringify(files.site)}, 'utf8'))
site.title = data.title
site.themeConfig.sidebar = data.sidebar
site.themeConfig.presmium = { form: data.form }

// The translations (P-123): a locale each, with its title, sidebar and labels; the language menu keeps the page.
const locales = data.locales.map(locale => locale.lang)
if (locales.length > 0) {
  site.locales = { root: { label: data.label, lang: site.lang } }
  for (const locale of data.locales) {
    site.locales[locale.lang] = { label: locale.label, lang: locale.lang, title: locale.title, themeConfig: { ...locale.labels.themeConfig, sidebar: locale.sidebar, ...locale.nav ? { nav: locale.nav } : {} } }
  }
}

// The Vite plugins of the deck's plugin packages: their \`vite.config.ts\`, as in the slides form, and those
// their Node entry adds (\`vitePlugins\`), with the plugin's configuration.
const deck = ${JSON.stringify(deck)}
site.vite = {
  plugins: [
    presmiumIR(${JSON.stringify(files.ir)}, ${JSON.stringify(files.searchDocuments)}, ${workspace ? JSON.stringify(workspace.endpoints) : 'undefined'}, locales),
    ...[${modules.vite.map((_, i) => `vite${i}`).join(', ')}].flatMap(config => config?.plugins ?? []),${nodePlugins.map(plugin => `\n    ${plugin},`).join('')}
  ],
  resolve: { dedupe: ['vue'] },${optimize.exclude.length > 0 ? `
  // The Presmium packages installed under node_modules, as from npm: their browser dependencies
  // pre-bundled, themselves never (the pages load their source).
  optimizeDeps: ${JSON.stringify(optimize)},` : ''}
}
${server}${inWorkspace}${framed}${shell.ogTitle ? OG_TITLE : ''}
// Local search over the IR text of each section: titles, narration, prose and code. The index is
// the renderer's own (see presmiumIR); the search box tokenizes queries as it does, Chinese into words.
site.themeConfig.search = {
  provider: 'local',
  options: {
    miniSearch: { options: { tokenize } },${labels.search ? `
    translations: ${JSON.stringify(labels.search)},` : ''}
    locales: Object.fromEntries(data.locales.filter(locale => locale.labels.search).map(locale => [locale.lang, { translations: locale.labels.search }])),
  },
}

export default site
`
}

function theme(preview?: { origins: string[], document: string }): string {
  return `${GENERATED}
import doc, { revision, translations } from 'virtual:presmium/ir'
import { createPresmiumTheme } from ${JSON.stringify(CLIENT_ENTRY)}
${preview ? `import { startWebPreview } from ${JSON.stringify(PREVIEW_AGENT)}
` : ''}import { components, plugins, viewers, restartable } from './addons.ts'

export default createPresmiumTheme({ doc, revision, translations, components, plugins, viewers, restartable${preview ? `, preview: page => startWebPreview(page, ${JSON.stringify(preview)})` : ''} })
`
}

function addons(modules: ClientModules): string {
  const load = (file: string) => `() => import(${JSON.stringify(file)})`
  const components = [...modules.components].map(([name, file]) => `  ${JSON.stringify(name)}: ssr ? never : ${load(file)},`)
  return `${GENERATED}
const ssr = import.meta.env.SSR
const never = () => new Promise(() => {})

export const restartable = ${modules.restartable === true}

export const components = {
${components.join('\n')}
}

export const plugins = ssr ? [] : [
${modules.plugins.map(file => `  ${load(file)},`).join('\n')}
]

export const viewers = ssr ? [] : [
${modules.viewers.map(({ name, file }) => `  { name: ${JSON.stringify(name)}, load: ${load(file)} },`).join('\n')}
]
`
}

export interface SiteInput {
  doc: IRDocument
  deck: DeckPaths
  modules: ClientModules
  options: WebRendererConfig
  workspace?: WorkspaceOptions
  translations?: { lang: string, doc: IRDocument }[]
  image?: string
  preview?: { origins: string[] }
}

export function localeFile(file: string, lang: string): string {
  return file.replace(/\.json$/, `.${lang}.json`)
}

function writePages(dir: string, pages: WebPage[], prefix: string, depth: number, workspace?: WorkspaceOptions): void {
  const names = new Set(pages.map(page => `${page.path}.md`))
  if (existsSync(dir)) for (const file of readdirSync(dir).filter(f => f.endsWith('.md') && !names.has(f))) rmSync(join(dir, file))
  pages.forEach((page, i) => {
    const prev = neighbour(pages[i - 1], prefix) ?? neighbourFrom(workspace?.neighbours?.prev, depth)
    const next = neighbour(pages[i + 1], prefix) ?? neighbourFrom(workspace?.neighbours?.next, depth)
    write(join(dir, `${page.path}.md`), pageMarkdown(page, prev, next))
  })
}

export function writeSite(workDir: string, input: SiteInput): void {
  const files = siteFiles(workDir)
  const { doc, modules, options, workspace } = input
  const pages = toPages(doc)
  const translations: Translation[] = (input.translations ?? []).map(t => ({ ...t, pages: translationPages(t.doc, pages) }))
  const others = workspace?.search ?? []
  write(files.ir, JSON.stringify(doc))
  write(files.searchDocuments, JSON.stringify([...searchDocuments(doc, options.base), ...others]))
  for (const { lang, doc: translated, pages: own } of translations) {
    write(localeFile(files.ir, lang), JSON.stringify(translated))
    write(localeFile(files.searchDocuments, lang), JSON.stringify([...searchDocuments(translated, `${options.base}${lang}/`, own), ...others]))
  }
  write(files.site, JSON.stringify(siteData(doc, options, translations, workspace)))
  write(join(workDir, '.gitignore'), '*\n')
  linkDependencies(files.root)
  const optimize = optimizeDeps(files.root, browserPackages(modules))
  write(join(files.root, '.vitepress/config.mjs'), config(options, files, modules, input.deck, workspace, input.image, optimize, input.preview))
  write(join(files.root, '.vitepress/theme/index.ts'), theme(input.preview && { origins: input.preview.origins, document: workspace?.document ?? '' }))
  write(join(files.root, '.vitepress/theme/addons.ts'), addons(modules))
  const depth = depthOf(workspace?.document ?? '')
  writePages(files.root, pages, '', depth, workspace)
  const langs = new Set(translations.map(t => t.lang))
  for (const entry of readdirSync(files.root, { withFileTypes: true })) {
    if (entry.isDirectory() && !entry.name.startsWith('.') && !['public', 'node_modules'].includes(entry.name) && !langs.has(entry.name)) rmSync(join(files.root, entry.name), { recursive: true, force: true })
  }
  for (const { lang, pages: own } of translations) writePages(join(files.root, lang), own, `/${lang}`, depth + 1, workspace)
  const deckPublic = join(input.deck.deckDir, 'public')
  if (existsSync(deckPublic)) copyDir(deckPublic, files.publicDir)
  write(join(files.publicDir, FONT_LICENSE), fontLicense(import.meta.url))
}
