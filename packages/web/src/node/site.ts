import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, readlinkSync, rmSync, symlinkSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { formLinks, renderPage, sidebar } from '../domain/index.ts'
import type { WebDocument } from '../domain/index.ts'
import type { LoadedDeck } from './deck.ts'

/** Generated VitePress project of a deck, relative to the deck directory. */
export const SITE_DIR = '.presmium/web'

const CLIENT_ENTRY = fileURLToPath(new URL('../client/index.ts', import.meta.url))
const TOKENIZER = fileURLToPath(new URL('../domain/search.ts', import.meta.url))
const GENERATED = '// Generated by presmium-web from the deck; do not edit.'

export interface SiteOptions {
  base: string
}

/** Writes a file only when its content changes, so the dev server reloads only what changed. */
function write(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
}

/**
 * Links the web package's own `vitepress` and `vue` into the generated project,
 * so they resolve from its root whatever the deck itself depends on.
 */
function linkDependencies(root: string): void {
  const require = createRequire(import.meta.url)
  for (const name of ['vitepress', 'vue']) {
    const target = dirname(require.resolve(`${name}/package.json`))
    const link = join(root, 'node_modules', name)
    if (existsSync(link) && readlinkSync(link) === target) continue
    rmSync(link, { force: true })
    mkdirSync(dirname(link), { recursive: true })
    symlinkSync(target, link, 'junction')
  }
}

function config(deck: LoadedDeck, doc: WebDocument, options: SiteOptions): string {
  const { slidesUrl } = doc.options
  const site = {
    title: doc.title,
    lang: 'zh-CN',
    base: options.base,
    cleanUrls: false,
    // Slides may link to slide numbers or files that have no page in the web form.
    ignoreDeadLinks: true,
    themeConfig: {
      sidebar: sidebar(doc),
      nav: slidesUrl ? [{ text: '幻灯片', link: slidesUrl }] : [],
      outline: { level: [2, 3], label: '本页大纲' },
      docFooter: { prev: '上一节', next: '下一节' },
      sidebarMenuLabel: '目录',
      returnToTopLabel: '回到顶部',
      darkModeSwitchLabel: '外观',
      presmium: {
        options: doc.options,
        links: formLinks(doc),
        config: deck.headmatter.presmium ?? {},
      },
    },
  }
  return `${GENERATED}
import { tokenize } from ${JSON.stringify(TOKENIZER)}

const site = ${JSON.stringify(site, null, 2)}

// Local search over titles, content, notes and code; Chinese is split into words.
site.themeConfig.search = {
  provider: 'local',
  options: {
    miniSearch: { options: { tokenize } },
    translations: {
      button: { buttonText: '搜索', buttonAriaLabel: '搜索' },
      modal: {
        displayDetails: '显示详细列表',
        resetButtonTitle: '清除',
        backButtonTitle: '关闭搜索',
        noResultsText: '没有结果',
        footer: { selectText: '选择', navigateText: '切换', closeText: '关闭' },
      },
    },
  },
}

export default site
`
}

function theme(): string {
  return `${GENERATED}
import { createPresmiumTheme } from ${JSON.stringify(CLIENT_ENTRY)}
import { components, plugins } from './addons.ts'

export default createPresmiumTheme({ components, plugins })
`
}

/** Addon components and kernel plugins, loaded lazily so the server render never runs them. */
function addons(deck: LoadedDeck): string {
  const components = [...deck.client.components].map(([name, file]) => `  ${JSON.stringify(name)}: () => import(${JSON.stringify(file)}),`)
  const plugins = deck.client.plugins.map(file => `  () => import(${JSON.stringify(file)}),`)
  return `${GENERATED}
export const components = {
${components.join('\n')}
}

export const plugins = [
${plugins.join('\n')}
]
`
}

/** Writes the VitePress project of the deck into `<deckDir>/.presmium/web` and returns its root. */
export function writeSite(deck: LoadedDeck, doc: WebDocument, options: SiteOptions): string {
  const root = join(deck.dir, SITE_DIR)
  write(join(root, '.gitignore'), '*\n')
  linkDependencies(root)
  write(join(root, '.vitepress/config.mjs'), config(deck, doc, options))
  write(join(root, '.vitepress/theme/index.ts'), theme())
  write(join(root, '.vitepress/theme/addons.ts'), addons(deck))
  const pages = new Set(doc.pages.map(page => `${page.path}.md`))
  for (const file of readdirSync(root).filter(f => f.endsWith('.md') && !pages.has(f))) rmSync(join(root, file))
  for (const page of doc.pages) write(join(root, `${page.path}.md`), renderPage(page))
  const publicDir = join(deck.dir, 'public')
  if (existsSync(publicDir)) cpSync(publicDir, join(root, 'public'), { recursive: true })
  return root
}
