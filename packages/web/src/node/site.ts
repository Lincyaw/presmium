import { existsSync, mkdirSync, readdirSync, readFileSync, readlinkSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import type { IRDocument } from '@presmium/kernel'
import { formOptions, pageMarkdown, searchMarkdown, sidebar, toPages } from '../domain/index.ts'
import type { FormOptions, WebRendererConfig } from '../domain/index.ts'
import { clientModules } from './addons.ts'

const CLIENT_ENTRY = fileURLToPath(new URL('../client/index.ts', import.meta.url))
const SEARCH = fileURLToPath(new URL('../domain/search.ts', import.meta.url))
const VITE_PLUGIN = fileURLToPath(new URL('./vite.ts', import.meta.url))
const GENERATED = '// Generated by @presmium/web from the IR; do not edit.'

/**
 * Layout of a working directory: the VitePress project in `site/`; the IR,
 * the search texts and the site data next to it, outside the project. The
 * project's files do not change with the IR (its config reads the site data
 * when it loads), so a dev server never restarts while the source is edited.
 */
export function siteFiles(workDir: string) {
  return {
    root: join(workDir, 'site'),
    ir: join(workDir, 'ir.json'),
    search: join(workDir, 'search.json'),
    site: join(workDir, 'site.json'),
    publicDir: join(workDir, 'site', 'public'),
  }
}

/** Writes a file only when its content changes, so the dev server reloads only what changed. */
export function write(file: string, content: string | Buffer): void {
  if (existsSync(file) && readFileSync(file).equals(Buffer.from(content))) return
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
}

/** Copies a directory file by file with `write`: unchanged files are not touched. */
function copyDir(from: string, to: string): void {
  for (const file of readdirSync(from, { recursive: true, encoding: 'utf8' })) {
    const source = join(from, file)
    if (statSync(source).isFile()) write(join(to, file), readFileSync(source))
  }
}

/** Links the web package's own `vitepress` and `vue` into the project, so they resolve from its root. */
function linkDependencies(root: string): void {
  const require = createRequire(import.meta.url)
  for (const name of ['vitepress', 'vue']) {
    const target = dirname(require.resolve(`${name}/package.json`))
    const link = join(root, 'node_modules', name)
    if (existsSync(link) && readlinkSync(link) === target) continue
    rmSync(link, { force: true })
    mkdirSync(dirname(link), { recursive: true })
    symlinkSync(target, link, 'junction')
  }
}

/** What the site shows of the IR outside the page bodies: the title, the sidebar and the links to the slides form. */
export interface SiteData {
  title: string
  sidebar: ReturnType<typeof sidebar>
  form: FormOptions
}

export function siteData(doc: IRDocument): SiteData {
  return {
    title: doc.meta.title,
    sidebar: sidebar(doc, toPages(doc)),
    form: formOptions(doc.config.presmium, doc.config.renderers),
  }
}

function config(options: WebRendererConfig, files: ReturnType<typeof siteFiles>): string {
  const site = {
    lang: options.lang,
    base: options.base,
    cleanUrls: false,
    // Links in the prose may point to files that have no page in the web form.
    ignoreDeadLinks: true,
    themeConfig: {
      outline: { level: [2, 3], label: '本页大纲' },
      sidebarMenuLabel: '目录',
      returnToTopLabel: '回到顶部',
      darkModeSwitchLabel: '外观',
    },
  }
  return `${GENERATED}
import { readFileSync } from 'node:fs'
import { searchableHtml, tokenize } from ${JSON.stringify(SEARCH)}
import { presmiumIR } from ${JSON.stringify(VITE_PLUGIN)}

const SEARCH_TEXTS = ${JSON.stringify(files.search)}
const site = ${JSON.stringify(site, null, 2)}

// Read when the config loads, so this file stays the same while the IR changes.
const data = JSON.parse(readFileSync(${JSON.stringify(files.site)}, 'utf8'))
site.title = data.title
site.themeConfig.sidebar = data.sidebar
site.themeConfig.presmium = { form: data.form }

site.vite = {
  plugins: [presmiumIR(${JSON.stringify(files.ir)})],
  resolve: { dedupe: ['vue'] },
}

// Local search over the IR text of each page: titles, narration, prose and code.
// Chinese is split into words.
site.themeConfig.search = {
  provider: 'local',
  options: {
    miniSearch: { options: { tokenize } },
    _render(src, env, md) {
      md.render(src, env)
      if (env.frontmatter?.search === false) return ''
      const text = JSON.parse(readFileSync(SEARCH_TEXTS, 'utf8'))[env.relativePath]
      return text ? searchableHtml(md.render(text, env)) : ''
    },
    translations: {
      button: { buttonText: '搜索', buttonAriaLabel: '搜索' },
      modal: {
        displayDetails: '显示详细列表',
        resetButtonTitle: '清除',
        backButtonTitle: '关闭搜索',
        noResultsText: '没有结果',
        footer: { selectText: '选择', navigateText: '切换', closeText: '关闭' },
      },
    },
  },
}

export default site
`
}

function theme(): string {
  return `${GENERATED}
import doc from 'virtual:presmium/ir'
import { createPresmiumTheme } from ${JSON.stringify(CLIENT_ENTRY)}
import { components, plugins, viewers } from './addons.ts'

export default createPresmiumTheme({ doc, components, plugins, viewers })
`
}

/** Plugin components, kernel plugins and viewer plugins, loaded lazily so the server render never runs them. */
function addons(deckDir: string, plugins: readonly string[]): string {
  const modules = clientModules(deckDir, plugins)
  const components = [...modules.components].map(([name, file]) => `  ${JSON.stringify(name)}: () => import(${JSON.stringify(file)}),`)
  const loaders = (files: string[]) => files.map(file => `  () => import(${JSON.stringify(file)}),`).join('\n')
  return `${GENERATED}
export const components = {
${components.join('\n')}
}

export const plugins = [
${loaders(modules.plugins)}
]

export const viewers = [
${loaders(modules.viewers)}
]
`
}

export interface SiteInput {
  /** The document as published (see `publishedDocument`). */
  doc: IRDocument
  deckDir: string
  plugins: readonly string[]
  options: WebRendererConfig
}

/**
 * Writes the IR, the search texts, the site data and the VitePress project
 * (config, theme, one Markdown page per page of the document). Only files
 * whose content changed are written: in a dev server, editing the source
 * rewrites the IR (pushed to the pages) and at most the pages' Markdown
 * (hot updated); the config changes only with the renderer options, the
 * theme only with the plugins' client modules.
 */
export function writeSite(workDir: string, input: SiteInput): void {
  const files = siteFiles(workDir)
  const { doc } = input
  const pages = toPages(doc)
  write(files.ir, JSON.stringify(doc))
  write(files.search, JSON.stringify(Object.fromEntries(pages.map(page => [`${page.path}.md`, searchMarkdown(doc, page)]))))
  write(files.site, JSON.stringify(siteData(doc)))
  write(join(workDir, '.gitignore'), '*\n')
  linkDependencies(files.root)
  write(join(files.root, '.vitepress/config.mjs'), config(input.options, files))
  write(join(files.root, '.vitepress/theme/index.ts'), theme())
  write(join(files.root, '.vitepress/theme/addons.ts'), addons(input.deckDir, input.plugins))
  const names = new Set(pages.map(page => `${page.path}.md`))
  for (const file of readdirSync(files.root).filter(f => f.endsWith('.md') && !names.has(f))) rmSync(join(files.root, file))
  for (const page of pages) write(join(files.root, `${page.path}.md`), pageMarkdown(page))
  const deckPublic = join(input.deckDir, 'public')
  if (existsSync(deckPublic)) copyDir(deckPublic, files.publicDir)
}
